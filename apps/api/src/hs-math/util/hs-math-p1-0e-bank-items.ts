/**
 * P1-0E 第一章正式题库数据（仅本地文件建设，不写库）。
 * specialtyCode=rja-ch1；KP 以种子/库中真实 code 为准。
 */
export type BankItem = {
  code: string
  specialtyCode: string
  categoryCode: string
  qtype: 'single' | 'multi' | 'judge' | 'numeric'
  difficulty: 1 | 2 | 3
  stem: string
  options?: { options: Array<{ id: string; text: string }> } | null
  answerPayload: Record<string, unknown>
  analysis: string
  knowledgePointCodes: string[]
  primaryKnowledgePointCode: string
}

const SP = 'rja-ch1'

function c(n: number) {
  return `HSMA-RJA-CH01-${String(n).padStart(4, '0')}`
}

function single(
  n: number,
  cat: string,
  diff: 1 | 2 | 3,
  stem: string,
  opts: [string, string, string, string],
  ans: 'A' | 'B' | 'C' | 'D',
  analysis: string,
  kps: string[],
  primary: string,
): BankItem {
  return {
    code: c(n),
    specialtyCode: SP,
    categoryCode: cat,
    qtype: 'single',
    difficulty: diff,
    stem,
    options: {
      options: [
        { id: 'A', text: opts[0] },
        { id: 'B', text: opts[1] },
        { id: 'C', text: opts[2] },
        { id: 'D', text: opts[3] },
      ],
    },
    answerPayload: { kind: 'single', optionId: ans },
    analysis,
    knowledgePointCodes: kps,
    primaryKnowledgePointCode: primary,
  }
}

function multi(
  n: number,
  cat: string,
  diff: 1 | 2 | 3,
  stem: string,
  opts: Array<{ id: string; text: string }>,
  ans: string[],
  analysis: string,
  kps: string[],
  primary: string,
): BankItem {
  return {
    code: c(n),
    specialtyCode: SP,
    categoryCode: cat,
    qtype: 'multi',
    difficulty: diff,
    stem,
    options: { options: opts },
    answerPayload: { kind: 'multi', optionIds: ans },
    analysis,
    knowledgePointCodes: kps,
    primaryKnowledgePointCode: primary,
  }
}

function judge(
  n: number,
  cat: string,
  diff: 1 | 2 | 3,
  stem: string,
  value: boolean,
  analysis: string,
  kps: string[],
  primary: string,
): BankItem {
  return {
    code: c(n),
    specialtyCode: SP,
    categoryCode: cat,
    qtype: 'judge',
    difficulty: diff,
    stem,
    answerPayload: { kind: 'judge', value },
    analysis,
    knowledgePointCodes: kps,
    primaryKnowledgePointCode: primary,
  }
}

function numeric(
  n: number,
  cat: string,
  diff: 1 | 2 | 3,
  stem: string,
  value: string,
  analysis: string,
  kps: string[],
  primary: string,
): BankItem {
  return {
    code: c(n),
    specialtyCode: SP,
    categoryCode: cat,
    qtype: 'numeric',
    difficulty: diff,
    stem,
    answerPayload: {
      kind: 'numeric',
      value,
      toleranceAbs: 0,
      toleranceRel: 0,
    },
    analysis,
    knowledgePointCodes: kps,
    primaryKnowledgePointCode: primary,
  }
}

